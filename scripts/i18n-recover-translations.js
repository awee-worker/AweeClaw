/**
 * 从 git 历史中恢复原始硬编码文本，生成正确的翻译
 * 
 * 用法：node scripts/i18n-recover-translations.js
 */

const { execSync } = require('child_process')
const fs = require('fs')
const path = require('path')

const enUSPath = path.join(__dirname, '../src/renderer/i18n/locales/enUS.ts')
const zhCNPath = path.join(__dirname, '../src/renderer/i18n/locales/zhCN.ts')

function parseKeys(content) {
  const keys = {}
  const regex = /['"]([a-zA-Z0-9_.]+)['"]:\s*'((?:[^'\\]|\\.)*)'/g
  let match
  while ((match = regex.exec(content)) !== null) {
    keys[match[1]] = match[2]
  }
  return keys
}

const enKeys = parseKeys(fs.readFileSync(enUSPath, 'utf-8'))
const zhKeys = parseKeys(fs.readFileSync(zhCNPath, 'utf-8'))

// Find all t() keys used in code
function findTKeysInCode(dir) {
  const keys = new Set()
  function scanDir(d) {
    const entries = fs.readdirSync(d, { withFileTypes: true })
    for (const entry of entries) {
      const fullPath = path.join(d, entry.name)
      if (entry.isDirectory() && !entry.name.startsWith('.') && entry.name !== 'node_modules' && entry.name !== 'i18n') {
        scanDir(fullPath)
      } else if (/\.(tsx|ts)$/.test(entry.name)) {
        const content = fs.readFileSync(fullPath, 'utf-8')
        const regex = /t\(\s*'([a-zA-Z0-9_.]+)'/g
        let match
        while ((match = regex.exec(content)) !== null) {
          keys.add(match[1])
        }
      }
    }
  }
  scanDir(dir)
  return keys
}

const usedKeys = findTKeysInCode(path.join(__dirname, '../src/renderer'))

// Find keys with placeholder translations (generated by fix-missing-keys)
const placeholderKeys = []
for (const key of usedKeys) {
  const enVal = enKeys[key] || ''
  const zhVal = zhKeys[key] || ''
  // Check if it's a placeholder (starts with [ or is just a camelCase conversion)
  if (zhVal.startsWith('[') || (!enVal && !zhVal)) {
    placeholderKeys.push(key)
  }
}

console.log(`Keys with placeholder translations: ${placeholderKeys.length}`)

if (placeholderKeys.length === 0) {
  console.log('No placeholder keys to fix!')
  process.exit(0)
}

// Get list of modified files
const modifiedFiles = execSync('git diff --name-only HEAD', { cwd: path.join(__dirname, '..'), encoding: 'utf-8' })
  .split('\n')
  .filter(f => f.endsWith('.tsx') || f.endsWith('.ts'))
  .filter(f => !f.includes('i18n/'))

console.log(`Modified files to scan: ${modifiedFiles.length}`)

// For each modified file, get original content from git and extract hardcoded i18n
const recoveredTranslations = {}

for (const file of modifiedFiles) {
  try {
    const originalContent = execSync(`git show HEAD:${file}`, { 
      cwd: path.join(__dirname, '..'), 
      encoding: 'utf-8',
      maxBuffer: 10 * 1024 * 1024 
    })
    
    if (!originalContent.includes("language === 'zh'")) continue
    
    const currentContent = fs.readFileSync(path.join(__dirname, '..', file), 'utf-8')
    
    // Find t('key', language) calls in current content
    const tKeyRegex = /t\(\s*'([a-zA-Z0-9_.]+)'\s*,\s*language/g
    let match
    while ((match = tKeyRegex.exec(currentContent)) !== null) {
      const key = match[1]
      if (!placeholderKeys.includes(key)) continue
      
      // Find the position in current content
      const tCallStart = match.index
      
      // Find the corresponding position in original content
      // Look for the same t() call pattern but it won't exist in original
      // Instead, look for the text around the t() call to find the original hardcoded text
      
      // Get context around the t() call (50 chars before and after)
      const contextBefore = currentContent.substring(Math.max(0, tCallStart - 100), tCallStart)
      const contextAfter = currentContent.substring(tCallStart, tCallStart + 200)
      
      // Try to find the same context in original content
      // Use the text before the t() call as anchor
      const anchorText = contextBefore.substring(contextBefore.lastIndexOf('\n') + 1)
      if (!anchorText.trim()) continue
      
      const origIdx = originalContent.indexOf(anchorText)
      if (origIdx === -1) continue
      
      // Look for language === 'zh' pattern near this position
      const searchStart = origIdx
      const searchEnd = Math.min(originalContent.length, origIdx + 300)
      const nearbyText = originalContent.substring(searchStart, searchEnd)
      
      const zhMatch = nearbyText.match(/language\s*===\s*'zh'\s*\?\s*'([^']*)'\s*:\s*'([^']*)'/)
      if (zhMatch) {
        recoveredTranslations[key] = { zh: zhMatch[1], en: zhMatch[2] }
        continue
      }
      
      // Try template literal pattern
      const tplMatch = nearbyText.match(/language\s*===\s*'zh'\s*\?\s*`([^`]*)`\s*:\s*`([^`]*)`/)
      if (tplMatch) {
        let en = tplMatch[2].replace(/\$\{([^}]+)\}/g, '{$1}')
        let zh = tplMatch[1].replace(/\$\{([^}]+)\}/g, '{$1}')
        recoveredTranslations[key] = { zh, en }
        continue
      }
    }
  } catch (err) {
    // File might not be in git yet
  }
}

console.log(`Recovered translations: ${Object.keys(recoveredTranslations).length}`)

// Update translation files
let enUSContent = fs.readFileSync(enUSPath, 'utf-8')
let zhCNContent = fs.readFileSync(zhCNPath, 'utf-8')

let enUpdated = 0
let zhUpdated = 0

for (const [key, val] of Object.entries(recoveredTranslations)) {
  // Update enUS.ts
  const enOld = `'${key}': '${enKeys[key] || ''}'`
  const enNew = `'${key}': '${val.en.replace(/'/g, "\\'")}'`
  if (enUSContent.includes(enOld)) {
    enUSContent = enUSContent.replace(enOld, enNew)
    enUpdated++
  }
  
  // Update zhCN.ts
  const zhOld = `'${key}': '${zhKeys[key] || ''}'`
  const zhNew = `'${key}': '${val.zh.replace(/'/g, "\\'")}'`
  if (zhCNContent.includes(zhOld)) {
    zhCNContent = zhCNContent.replace(zhOld, zhNew)
    zhUpdated++
  }
}

fs.writeFileSync(enUSPath, enUSContent, 'utf-8')
fs.writeFileSync(zhCNPath, zhCNContent, 'utf-8')

console.log(`\n✓ Updated ${enUpdated} English translations`)
console.log(`✓ Updated ${zhUpdated} Chinese translations`)

// Output remaining unrecovered keys
const stillMissing = placeholderKeys.filter(k => !recoveredTranslations[k])
if (stillMissing.length > 0) {
  console.log(`\n⚠️  Still missing proper translations for ${stillMissing.length} keys:`)
  stillMissing.slice(0, 20).forEach(k => console.log(`  - ${k}`))
  if (stillMissing.length > 20) console.log(`  ... and ${stillMissing.length - 20} more`)
}
